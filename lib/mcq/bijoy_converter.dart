  /// লেখাটা বিজয়ে লেখা কিনা আন্দাজ করা
  static bool looksLikeBijoy(String text) {
    if (text.trim().isEmpty) return false;
    final bn = _bengali.allMatches(text).length;
    final marks = _bijoyMarks.allMatches(text).length;
    final letters = RegExp(r'[A-Za-z]').allMatches(text).length;
    if (bn > letters) return false; // আগে থেকেই ইউনিকোড বাংলা
    if (letters == 0) return false;
    final words = _bijoyWords.allMatches(text).length;
    return marks >= 3 && (marks / letters > 0.02 || words >= 2);
  }

  static const _consonants = 'কখগঘঙচছজঝঞটঠডঢণতথদধনপফবভমযরলশষসহড়ঢ়য়ৎ';
  static bool _isCons(String c) => _consonants.contains(c);

  /// বিজয় → ইউনিকোড
  static String convert(String input) {
    final sb = StringBuffer();
    var i = 0;
    while (i < input.length) {
      var matched = false;
      for (final k in _keys) {
        if (input.startsWith(k, i)) {
          sb.write(_map[k]);
          i += k.length;
          matched = true;
          break;
        }
      }
      if (!matched) {
        sb.write(input[i]);
        i++;
      }
    }
    return reorder(sb.toString(), moveReph: true);
  }

  /// [start] থেকে শুরু হওয়া যুক্তবর্ণের শেষ index (exclusive)
  static int _clusterEnd(List<String> s, int start) {
    var j = start;
    if (j >= s.length || !_isCons(s[j])) return start;
    j++;
    while (j + 1 < s.length && s[j] == '্' && _isCons(s[j + 1])) {
      j += 2;
    }
    // র‌্য (ZWNJ + ্য)
    if (j + 2 < s.length && s[j] == '‌' && s[j + 1] == '্' && _isCons(s[j + 2])) j += 3;
    return j;
  }

  /// দেখানোর ক্রমে থাকা কার-চিহ্ন (ি ে ৈ) ও রেফ (র্) ঠিক ক্রমে আনা।
  /// PDF থেকে তোলা ইউনিকোড লেখাতেও কাজে লাগে, যেখানে "িক" এভাবে আসে।
  static String reorder(String text, {bool moveReph = false}) {
    final s = text.split('');
    final out = <String>[];
    var i = 0;
    while (i < s.length) {
      final c = s[i];
      if ((c == 'ি' || c == 'ে' || c == 'ৈ') && i + 1 < s.length && _isCons(s[i + 1])) {
        final end = _clusterEnd(s, i + 1);
        out.addAll(s.sublist(i + 1, end));
        // ে + া = ো, ে + ৗ = ৌ
        if (c == 'ে' && end < s.length && s[end] == 'া') {
          out.add('ো');
          i = end + 1;
        } else if (c == 'ে' && end < s.length && s[end] == 'ৗ') {
          out.add('ৌ');
          i = end + 1;
        } else {
          out.add(c);
          i = end;
        }
        continue;
      }
      out.add(c);
      i++;
    }
    // রেফ: বিজয়ে "র্" অক্ষরের পরে বসে, ইউনিকোডে আগে বসবে
    final r = <String>[];
    for (var k = 0; k < out.length; k++) {
      if (moveReph &&
          out[k] == 'র' &&
          k + 1 < out.length &&
          out[k + 1] == '্' &&
          (k == 0 || out[k - 1] != '্') &&
          (k + 2 >= out.length || out[k + 2] != '‌')) {
        // পেছনে যাওয়া: কার/চিহ্ন বাদ দিয়ে আগের যুক্তবর্ণের শুরু খোঁজা
        var p = r.length;
        while (p > 0 && 'ািীুূৃেৈোৌংঃঁ'.contains(r[p - 1])) {
          p--;
        }
        var start = p;
        if (start > 0 && _isCons(r[start - 1])) {
          start--;
          while (start >= 2 && r[start - 1] == '্' && _isCons(r[start - 2])) {
            start -= 2;
          }
          r.insertAll(start, ['র', '্']);
          k++;
          continue;
        }
      }
      r.add(out[k]);
    }
    return r.join();
  }

  /// ইউনিকোড লেখায় "দেখানোর ক্রম" সমস্যা আছে কিনা (শব্দের শুরুতে ি/ে/ৈ)
  static bool hasVisualOrder(String text) {
    final bad = RegExp(r'(^|[\s(])[িেৈ][কখগঘঙচছজঝঞটঠডঢণতথদধনপফবভমযরলশষসহ]').allMatches(text).length;
    return bad >= 3;
  }
